export function getModules(language = "de") {
  const l = LANGUAGES[language];
  return moduleData.map((m) => ({
    ...m,
    tasks: m
      .tasks(l)
      .map((t, i) => ({
        ...t,
        id: `${m.id}-${i + 1}`,
        xp: t.type === "portfolio" ? 30 : 40,
        ...(t.key === "filename"
          ? { answer: `2026-03-07_${language}_S03.wav` }
          : {}),
      })),
  }));
}

