export function countProtocol(l) {
  const t = l.terminology;
  return `P1. Авторський протокол підрахунку\nМатеріал: ${t.forms.join(" ")}\nРахуємо лише окремі слова, пунктуацію не враховуємо; регістр ігноруємо.\nКожна позиція слова – одне слововживання (C01). Різне написання після цієї обробки – різні типи словоформ (C02).\nДля цього прикладу всі три позиції віднесено до леми ${t.lemma} (C03). Це задана навчальна лематизація, а не результат роботи програми.`;
}
export function responseProtocol(l) {
  const t = l.terminology;
  return `P2. Два авторські протоколи з однаковою назвою «${t.responseTerm}»\nR1: ${t.responseA}\nУкраїнською: від подання запиту до початку першої відповіді. Для одного умовного запиту – 240 мс.\nR2: ${t.responseB}\nУкраїнською: від подання запиту до отримання всієї відповіді. Для того самого запиту – 900 мс.\nЧерез різні кінцеві події ці протоколи визначають різні показники часу відповіді; дані вигадані, записів або експерименту в наборі немає.`;
}
