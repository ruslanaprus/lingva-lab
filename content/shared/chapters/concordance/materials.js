export const datasetFor = (l) => prepareConcordance(l.concordance);
export function searchExample(l, preset, ids = []) {
  const d = datasetFor(l),
    s = { ...d.defaults, ...d.presets[preset] };
  return `Навчальний набір ${d.id}, версія ${d.version}\nЗапит: ${s.query}; тип: ${s.mode}; регістр: ${s.caseSensitive ? "враховано" : "не враховано"}\nКорпус: ${s.corpus}; жанр: ${s.genre}; рік: ${s.year}; POS: ${s.pos}; вікно: ${s.window}; порядок: ${s.sort}\n${ids
    .map((id) => {
      const doc = d.documents.find((d) => d.id === id);
      return `${doc.id} | ${doc.title} | ${doc.genre} | ${doc.year}\n${doc.text}`;
    })
    .join("\n\n")}`;
}
