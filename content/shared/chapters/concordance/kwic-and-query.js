import { ask, enter, practice } from "./activities.js";
import { searchExample } from "./materials.js";
export function kwic(l) {
  const m = l.concordance;
  return [
    ask({
      id: "concordance-why-context",
      stage: "kwic",
      title: "Знайти слово – ще не зрозуміти вислів",
      paragraphs: [
        `Перекладач знайшов «${m.word}» у кількох текстах і хоче вибрати український відповідник. Сам список слів не показує, хто говорить, що саме названо й до кого звертаються. Укладач словника, дослідник прохань і викладач також потребують прикладу в контексті.`,
        "Конкорданс – це список знайдених уживань із навколишнім текстом. KWIC означає Key Word in Context: збіг стоїть посередині, ліворуч і праворуч показано частини контексту. Ключове слово тут – те, що знайшов запит, а не автоматично найважливіше слово документа. У панелі вище видно три колонки; натисніть виділений збіг, щоб прочитати більше.",
      ],
      example: searchExample(l, "initial", ["C02", "C06"]),
      preset: "initial",
      prompt: "Що найкраще дає підставу вибрати значення слова у знайденому рядку?",
      options: [
        "Перші п’ять рядків у початковому порядку: вони представляють основні значення, а решту можна використати для підтвердження.",
        "Речення та потрібний ширший контекст, жанр і джерело; порядок рядка чи сам збіг ще не визначають значення.",
        "Найчастіша сусідня форма в цьому списку: вона задає значення всім уживанням, якщо пошук виконано за однаковою лемою.",
      ],
      answer: 1,
      explain:
        "Один запит може повернути різні значення, цитати й пояснення слова. Їх потрібно розрізнити читанням.",
      sources: ["concordance-guide"],
    }),
    ask({
      id: "concordance-read-kwic",
      stage: "kwic",
      title: "Прочитайте рядок із трьох частин",
      paragraphs: [
        "Лівий контекст передує збігу, правий іде після нього. Колонки вирівняно навколо слова, щоб легше помічати повторювані конструкції. Край видимого рядка не обов’язково є початком або кінцем речення. Знак ∅ у нашій панелі означає, що з цього боку вже немає токенів у документі.",
        "Нижче кожного рядка є ID документа, жанр, рік, джерело, лема й POS. POS – позначка частини мови: наприклад, NOUN для іменника або VERB для дієслова. Знак ? означає, що мітку не задано. Натискання слова розгортає контекст; ID відкриває джерело. Спершу розгляньте початковий приклад без зміни параметрів.",
      ],
      preset: "initial",
      prompt:
        "Лівий контекст починається посеред речення. Що варто зробити перед тлумаченням?",
      options: [
        "Вважати перше видиме слово початком речення й визначити його роль за великою літерою; ширина вікна не змінює межі речення.",
        "Відкинути цей рядок як неповний документ; збережений край KWIC свідчить, що початковий текст втрачено під час підготовки.",
        "Розгорнути джерело й перевірити справжні межі; коротке вікно лише приховало частину збереженого тексту.",
      ],
      answer: 2,
      explain:
        "Ширина показу й межі речення – різні речі. Перш ніж робити висновок, поверніться до достатнього контексту.",
    }),
    enter({
      id: "concordance-hits-documents",
      stage: "kwic",
      title: "Збіги й документи – різні лічильники",
      paragraphs: [
        `Натисніть кнопку для вправи, потім «Знайти». Тип – словоформа, запит «${m.word}», регістр не враховано, корпус – усі тексти, фільтри – усі. На сторінці видно по п’ять рядків, а загальний лічильник охоплює весь результат.`,
        "У C11 слово трапляється двічі. Це два збіги в одному документі, а не два незалежні документи. На наступній сторінці можуть бути інші тексти; кнопки «Наступні» та «Попередні» змінюють показану частину списку, але не сам пошук.",
      ],
      example: searchExample(l, "initial", ["C11"]),
      preset: "initial",
      prompt:
        "Скільки різних документів містить початковий пошук? Уведіть число з лічильника «документів».",
      answer: String(m.expected.wordDocuments),
      extra: { numeric: true },
      explain:
        "Рахуємо різні ID документів серед усіх збігів, а не лише рядки першої сторінки.",
    }),
    practice({
      id: "concordance-navigate-first-search",
      stage: "kwic",
      minutes: 5,
      title: "Знайдіть рядок і поверніться до повного тексту",
      paragraphs: [
        "Спробуйте короткий маршрут у панелі. Виконайте початковий пошук, перейдіть на наступну сторінку, відкрийте один збіг і прочитайте весь документ. Потім відкрийте один із текстів через список «Тексти корпусу й довідка про розмітку». Порівняйте ці два шляхи до джерела.",
        "Панель має власні кнопки пошуку. Перевірка вправи розташована під цим поясненням. Повернутися до нього допоможе кнопка «Повернутися до вправи». Достатньо коротко назвати знайдені ID й те, що стало видно після розгортання.",
      ],
      preset: "initial",
      steps: [
        "Виконайте пошук і знайдіть, де показано всі збіги та кількість документів.",
        "Перейдіть на наступну сторінку й натисніть збіг; перевірте жанр і рік джерела.",
        "Поверніться до вправи й опишіть один фрагмент, якого не було видно в KWIC.",
      ],
      prompt:
        "Укажіть ID відкритого документа, його жанр і рік та коротко поясніть, чим повний текст доповнив рядок KWIC.",
      rubric: [
        "ID й метадані стосуються відкритого джерела.",
        "Видимий рядок відрізнено від повного документа.",
        "Результат дії описано конкретно, а не лише підтверджено натискання кнопок.",
      ],
    }),
  ];
}
export function query(l) {
  const m = l.concordance;
  return [
    enter({
      id: "concordance-fragment-false-match",
      stage: "query",
      title: "Частина слова знаходить і зайве",
      paragraphs: [
        `Пошук частини «${m.fragment}» перевіряє буквальний фрагмент усередині токена. Він може знайти словоформи, але також похідне слово або зовсім інший вираз. Виконайте цей пошук без додаткових фільтрів і знайдіть форму «${m.falseForm}».`,
        "Пошук словоформи в нашій панелі порівнює цілий токен; частина слова – входження фрагмента. Це різні умови. Межі токенів задають під час підготовки корпусу: апострофи, дефіси й пунктуація можуть опрацьовуватися по-різному в різних інструментах.",
      ],
      example: searchExample(l, "fragment", ["C08"]),
      preset: "fragment",
      prompt: `У якому документі знайдено «${m.falseForm}» – небажаний для нашого питання збіг фрагмента? Уведіть ID.`,
      answer: "C08",
      explain:
        "Технічно фрагмент знайдено правильно. Його відповідність мовному питанню потребує окремої перевірки.",
    }),
    enter({
      id: "concordance-case-comparison",
      stage: "query",
      title: "Що приховує чутливість до регістру",
      paragraphs: [
        `Порівняйте два пошуки словоформи «${m.word}»: спершу без урахування регістру, потім із прапорцем Case. Корпус і решта фільтрів мають лишитися однаковими. Перемикання прапорця почне діяти після натискання «Знайти».`,
        "Велика літера може бути наслідком початку речення або заголовка, а не окремого значення. Для німецької важливе також написання іменників із великої літери. Вибір режиму залежить від питання; не залишайте прапорець випадково від попереднього пошуку.",
      ],
      preset: "case",
      prompt:
        "На скільки збігів менше після ввімкнення Case порівняно з початковим пошуком? Уведіть різницю загальних лічильників.",
      answer: String(m.expected.wordHits - m.expected.caseHits),
      extra: { numeric: true },
      explain:
        "Зіставляємо виконані пошуки з однаковими фільтрами. Різниця показує втрачені за цією умовою форми, а не відмінність значень.",
    }),
    ask({
      id: "concordance-word-lemma",
      stage: "query",
      title: "Словоформа й лема відповідають на різні запити",
      paragraphs: [
        `Словоформа – конкретне написання в тексті. Лема – базова форма, записана в розмітці. Для леми «${m.lemma}» у наборі є, зокрема, форма «${m.variant}». Точний пошук початкової словоформи може її не знайти.`,
        "Лемний пошук не є розумінням значення й не зводиться до спільного початку слова. Він читає записану мітку. Якщо її немає або вона помилкова, результат буде неповним чи неточним. У нашому наборі розмічено лише вибрані слова; доступні мітки видно в контексті та annotation.csv.",
      ],
      example: searchExample(l, "lemma", ["C09"]),
      preset: "lemma",
      prompt: "Що найкраще описує різницю між двома режимами?",
      options: [
        "Словоформа шукає видимий запис, лема – значення відповідного поля розмітки; жоден режим сам не гарантує потрібного змісту.",
        "Лема шукає всі слова зі спільними початковими літерами; тому для неї можна не перевіряти похідні слова та омоніми в результатах.",
        "Словоформа потрібна тільки для невідомих слів, а лема автоматично відкидає назви, цитати й нерелевантні значення вже відомого слова.",
      ],
      answer: 0,
      explain:
        "Лема допомагає об’єднати задані форми, але якість залежить від розмітки та перевірки контексту.",
      sources: ["concordance-grac"],
    }),
    enter({
      id: "concordance-find-inflected-form",
      stage: "query",
      title: "Перевірте, яку форму пропустив перший пошук",
      paragraphs: [
        `Знайдіть лему «${m.lemma}» без фільтрів і прочитайте C09. У тексті є «${m.variant}». Потім повторіть пошук початкової словоформи «${m.word}» й перевірте, чому цього рядка немає.`,
        "Конкорданс за лемою все одно показує в центрі фактичну форму з тексту. Це допомагає дослідити словозміну й синтаксичне оточення. Не переписуйте цитату в початкову форму, коли зберігаєте приклад для словника або перекладацького рішення.",
      ],
      preset: "lemma",
      prompt: `Уведіть ID документа з формою «${m.variant}», яку не знаходить початковий точний пошук словоформи.`,
      answer: "C09",
      explain:
        "C09 містить іншу форму тієї самої записаної леми. Режим word не розширює її автоматично.",
    }),
    practice({
      id: "concordance-three-searches",
      stage: "query",
      minutes: 6,
      title: "Зіставте три пошуки одного явища",
      paragraphs: [
        `Проведіть три пошуки: словоформа «${m.word}», частина «${m.fragment}» і лема «${m.lemma}». Регістр не враховуйте, корпус – усі тексти, фільтри – усі. Після кожного запишіть загальну кількість збігів і документів, а не лише рядки на екрані.`,
        "Знайдіть один результат, який додала частина слова, і один, який додала лема. Поясніть, чому вони з’явилися. Більший список не завжди кращий: додаткові рядки можуть бути як потрібними формами, так і небажаними збігами.",
      ],
      preset: "initial",
      steps: [
        "Виконайте три запити, змінюючи лише потрібний тип і текст запиту.",
        "Збережіть лічильники й по одному ID, що пояснює відмінність.",
        "Для свого мовного питання оберіть початковий маршрут і назвіть його обмеження.",
      ],
      prompt:
        "Подайте невелику таблицю трьох пошуків, два конкретні приклади різниці та обґрунтований вибір режиму.",
      rubric: [
        "Параметри пошуків зіставні.",
        "Різницю пояснюють конкретні форми та ID.",
        "Кількість збігів не підміняє перевірки доречності.",
      ],
    }),
  ];
}
