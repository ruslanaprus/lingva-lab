import { ask, enter, practice } from "./activities.js";

export function ipaActivities(l) {
  const t = l.typography;
  return [
    ask({
      id: "unicode-ipa-purpose",
      stage: "ipa",
      minutes: 3,
      title: "Навіщо філологу клавіатура IPA?",
      paragraphs: [
        `IPA, або МФА, – Міжнародний фонетичний алфавіт: система символів для запису звуків мовлення. У ${t.ipaWord} початковий звук у нашому прикладі позначено ʃ. Написання слова й транскрипція – різні речі: клавіатура IPA вводить символи, але не слухає запис і не визначає вимову.`,
        "Реальні застосування: нотатка до словникової статті, пояснення вимови студентам, фонетичний коментар до перекладу, мітка в Praat TextGrid. У /…/ зазвичай подають фонемний запис, у […] – фонетичну транскрипцію за обраною точністю. Тут відтворюємо готові широкі фонетичні зразки; повний аналіз звуку буде в наступних розділах. Назва мови не визначає єдину вимову всіх її носіїв.",
      ],
      prompt: "Що робить Unicode-клавіатура IPA?",
      options: [
        "Вводить фонетичні символи як текст, а вимову й конвенцію визначає дослідник",
        "Автоматично доводить, як говорить кожен носій",
        "Замінює звук картинкою й гарантує пошук",
      ],
      answer: 0,
      explain:
        "Клавіатура – спосіб введення, а не автоматичний транскрибатор або доказ фонетичної інтерпретації.",
      sources: ["ipa-uk", "ipa", "keyman-ipa", "textgrid"],
    }),
    enter({
      id: "unicode-ipa-panel",
      stage: "ipa",
      minutes: 5,
      title: "Зберіть маленьку фонетичну мітку",
      paragraphs: [
        `Під полем є мала навчальна панель IPA, а не повна таблиця МФА. Для початкового звука ${t.ipaWord} складіть [ʃ]: натисніть [, ʃ і ]. На кнопці є код; натискання вставляє знак у позиції курсора або замінює виділений фрагмент. Латинська s чи послідовність sh не замінюють ʃ U+0283.`,
        "Натисніть «Порівняти NFC/NFD», звірте код і лише після цього подайте відповідь. Можна спершу навмисно ввести [s], дослідити відмінність і виправити її. Перегляд і вставлення не є спробою; спроба зберігається після кнопки перевірки. Ця мітка згодом може стати текстовим підписом в анотації запису.",
      ],
      symbols: [
        { text: "ʃ", label: "U+0283 – IPA-символ" },
        { text: "s", label: "U+0073 – інший знак" },
      ],
      prompt: "Подайте саме [ʃ], разом із квадратними дужками, без пробілів.",
      answer: "[ʃ]",
      palette: t.ipaPalette,
      explain:
        "Мітка містить справжній ʃ. Вона відтворює заданий символ, але ще не засвідчує аналізу власного запису.",
      sources: ["ipa", "keyman-ipa"],
    }),
    enter({
      id: "unicode-ipa-features",
      stage: "ipa",
      minutes: 5,
      title: `IPA: ${t.ipaFeature.toLocaleLowerCase("uk")}`,
      paragraphs: [
        t.ipaExplanation,
        `Відтворіть готовий рядок ${t.ipaRecord}. Звичайні літери введіть клавіатурою, спеціальні – панеллю. Якщо є комбінований знак, поставте курсор після базової літери й вставте його. Таблиця показує окрему кодову точку навіть тоді, коли знак приєднався до літери. У фонетичних нотатках називаємо джерело або навчальний статус, різновид вимови та конвенцію.`,
      ],
      example: `${t.ipaRecordWord}: ${t.ipaRecord}\nКонвенція: ${t.ipaVariety}`,
      prompt:
        "Уведіть наведений IPA-рядок зі справжніми знаками. Апостроф, двокрапка й окрема ~ не замінюють IPA-знаки.",
      answer: t.ipaRecord,
      palette: t.ipaPalette,
      explain:
        "Відтворено рядок обраної конвенції. Перевірка порівнює символи, а не оцінює вимову або акустичну точність.",
      sources: ["ipa", t.dictionarySource],
    }),
    ask({
      id: "unicode-ipa-evidence",
      stage: "ipa",
      minutes: 3,
      title: "Клавіатура не є джерелом вимови",
      paragraphs: [
        "Різні словники можуть подавати різновиди вимови, різну деталізацію та різні системи запису. Відмінність не слід одразу оголошувати помилкою або «лікувати» шрифтом. Перевірте легенду словника, позначку різновиду й за наявності аудіо.",
        "Якщо власний запис нечіткий, правильно позначити невпевненість і вказати, що треба переслухати. Не копіюйте словникову транскрипцію й не називайте її виміряним мовленням свого учасника. Для фонетичного дослідження потрібні сам запис, дозволене використання, межі та правила анотації.",
      ],
      prompt: "У двох словниках різні транскрипції слова. З чого почати перевірку?",
      options: [
        "З’ясувати різновид вимови, конвенцію й джерело; за наявності зіставити аудіо",
        "Вибрати зрозуміліший шрифт як доказ",
        "Оголосити один варіант єдиним для всіх носіїв",
      ],
      answer: 0,
      explain:
        "Джерело й конвенція допомагають пояснити відмінність. Набраний рядок не доводить, що так вимовив конкретний мовець.",
      sources: ["ipa", t.dictionarySource],
    }),
    practice({
      id: "unicode-ipa-keyboard-practice",
      stage: "ipa",
      minutes: 8,
      title: "Практика: словникова нотатка з Unicode-IPA",
      paragraphs: [
        "Відкрийте Keyman IPA (SIL) за посиланням: знайдіть «Try this keyboard» і «Keyboard help». Це справжнє введення IPA в Unicode; встановлення не потрібне. Клацніть поле й прочитайте схему саме цієї клавіатури – її послідовності не є правилами всіх IPA-панелей.",
        `Наберіть ʃ та ще один потрібний знак із ${t.ipaRecord}; скопіюйте їх в інспектор сайту. Створіть ipa-note.txt зі словом ${t.ipaRecordWord}, рядком, конвенцією (${t.ipaVariety}) та призначенням нотатки. Якщо Keyman недоступний, використайте панель сайту й назвіть її у методі. Це має бути доступний маршрут (посилання на доступний сервіс в мережі), а не удаване використання зовнішнього сервісу.`,
      ],
      steps: [
        "Перевірте коди двох знаків після введення й копіювання справжнього тексту.",
        "Збережіть нотатку як UTF-8; закрийте, відкрийте й перевірте, що IPA лишився текстом.",
        "Запишіть інструмент і результат; окремо вкажіть, що вимову не визначали з власного аудіо.",
      ],
      prompt:
        "Подайте IPA-нотатку: два перевірені знаки, спосіб введення, кодові точки, конвенція й повторне відкриття.",
      rubric: [
        "Два IPA-знаки введено й перевірено за кодами; названо фактичну клавіатуру або альтернативну панель.",
        "Нотатка містить слово, транскрипцію, конвенцію та статус навчального зразка.",
        "Є повторне відкриття або позначений план; звук не приписано неіснуючому учаснику.",
      ],
      sources: ["keyman-ipa", "ipa", "ipa-fonts"],
    }),
  ];
}
