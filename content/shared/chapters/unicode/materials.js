        content: `МАЙСТЕРНЯ СИМВОЛІВ / ${l.native}\nПотрібні навички розділів 1–3: знайти файл, залишити оригінал, створити робочу копію, відкрити UTF-8 і перевірити кодові точки. Спочатку прочитайте пояснення на сайті, input-guide.txt та editorial-brief.txt. Усі 7 файлів – UTF-8. Зразки навмисно містять різні символи; не виправляйте джерела.\n`,
