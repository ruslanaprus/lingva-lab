  const inputGuide = `ЯК ПРАЦЮВАТИ БЕЗ ДОСВІДУ\n1. Як у розділі 1, розпакуйте ZIP, збережіть його в original/, працюйте в working/, результати покладіть у results/.\n2. Windows: шукайте Параметри → Час і мова → Мова та регіон / Клавіатура. Перемикач і Win+Space залежать від налаштувань. Переглядач символів можна знайти пошуком «Таблиця символів»; встановлення нової мови не є обов’язковим.\n3. macOS: Системні параметри → Клавіатура → джерела вводу. Утримання літери або меню вводу → переглядач символів може дати діакритику. Конкретні скорочення залежать від версії й розкладки.\n4. Linux: у налаштуваннях клавіатури шукайте джерела вводу; переглядач символів і Compose залежать від середовища. На телефоні спробуйте утримання літери або системний вибір символів.\n5. Word: перевірте мову виділеного тексту в Рецензування / Мова. Google Docs: Файл → Мова; Writer: мова фрагмента в меню Інструменти → Мова. Назви залежать від версії. Зміна меню не виправляє вже набрані літери.\n6. Панель на сайті: введіть текст у полі; «Порівняти NFC/NFD» показує коди, форми й навчальний пошук, але не подає відповідь. Кнопки символів вставляють знак у позиції курсора. Після вставлення комбінованого знака перевірте його код.\n7. IPA (МФА) – Міжнародний фонетичний алфавіт. Панель сайту містить лише малу добірку. На https://keyman.com/keyboards/sil_ipa є «Try this keyboard» та Keyboard help: натисніть у полі, відкрийте схему й перевірте власний спосіб. Встановлення не потрібне. Якщо сервіс недоступний, скористайтеся панеллю сайту та офіційною IPA-таблицею.\n8. Збережіть справжній TXT у UTF-8. У Word не достатньо перейменувати DOCX; скористайтеся експортом у простий текст. Відкрийте копію знову й звірте коди та значення. PDF перевіряйте також копіюванням тексту, а не лише поглядом.\n9. Сайт не змінює вашу ОС і не перевіряє вміст зовнішніх файлів. Якщо інструмент недоступний, чесно позначте план і поверніться до виконання пізніше.\n`;
