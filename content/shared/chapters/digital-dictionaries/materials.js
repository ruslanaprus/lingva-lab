        content: `Реальні стартові ресурси: дивіться активні посилання в уроках і загальній довідці розділу. Ключі довідки:\n${resourceMap}\nПорівнюйте ${d.primaryName} та ${d.secondaryName}. Для української частини рішення є ресурси УМІФ. Сайти можуть змінювати інтерфейс; шукайте Search / Suche / Rechercher і довідку, а не кнопку певного кольору. Акаунт чи платна підписка не потрібні для навчальної альтернативи.`,
