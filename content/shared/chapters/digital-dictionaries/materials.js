export function entryCard(d) {
  return `E1. НАВЧАЛЬНА КАРТКА, авторське спрощення для курсу; не копія ${d.primaryName}.
Заголовне слово: ${d.headword}
Форма з тексту: ${d.form}
Речення з цією формою: ${d.formContext}
Підказка: ${d.formContextHelp}
Граматична довідка: ${d.grammar}
А1: ${d.other}
Приклад А1: ${d.otherContext}
А2: ${d.target}
Приклад А2: ${d.context}
Пояснення: ${d.contextHelp}
Форми: ${d.formNote}
Вимова (навчальна IPA): ${d.ipa}
${d.phoneticNote}
А1/А2 – наші локальні позначення, не номери значень у реальному словнику.
Картка охоплює лише два відібрані вживання; повного списку значень тут немає.`;
}

